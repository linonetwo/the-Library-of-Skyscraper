import test from 'node:test';
import assert from 'node:assert/strict';
test('MCP browser exposes replay seeks and rendered private state', {skip:process.env.ARENA_BROWSER!=='1',timeout:90000}, async t=>{
 const { Client }=await import('../tools/node_modules/@modelcontextprotocol/sdk/dist/esm/client/index.js');
 const { StdioClientTransport }=await import('../tools/node_modules/@modelcontextprotocol/sdk/dist/esm/client/stdio.js');
 const {fileURLToPath}=await import('node:url');
 const client=new Client({name:'replay-browser',version:'1'});
 await client.connect(new StdioClientTransport({command:process.execPath,args:[fileURLToPath(new URL('../tools/server.mjs',import.meta.url))],env:process.env,stderr:'pipe'}));
 t.after(()=>client.close());
 const call=async(name,args={})=>{const step = args.action?.type || name;
    const started = performance.now();
    console.log(`MCP START ${step}`);
    const response=await client.callTool({name,arguments:args});
    console.log(`MCP END ${step} ${Math.round(performance.now() - started)}ms`);assert.notEqual(response.isError,true,response.content[0].text);return JSON.parse(response.content[0].text);};
 const action=action=>call('Input.action',{action});
 await call('Page.open');
 t.after(async()=>{try{await call('Page.close');}catch{}});
 await action({type:'startTraining'});
 await action({type:'resetTraining'});
 await action({type:'openScripts'});
 await action({type:'loadScriptTemplate',template:'memory-gather'});
 await action({type:'publishScript'});
 await action({type:'openReplay'});
 let state=await call('Page.getState');
 assert(state.replay);
 await action({type:'seekReplay',operationIndex:state.replay.maxOperationIndex});
 state=await call('Page.getState');
 assert.equal(state.replay.operationIndex,state.replay.maxOperationIndex);
 assert.equal(state.replay.memory,'{}');
 await action({type:'playReplay'});
 await action({type:'pauseReplay'});
 await action({type:'closeReplay'});
 assert.equal((await call('Page.getState')).replay,null);
});
